"""Run every arm over every case and write the results.

Results are written from the run, never typed by hand. The report prints where each
arm wins and where it loses; no arm is expected to win everywhere, and the ones that
lose on a metric say so in the same table.

    python eval/run_benchmark.py --arms keyword exhaustive llm decider
    python eval/run_benchmark.py --arms decider --limit 5     # a cheap smoke pass
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
import time
from typing import Any

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(HERE))

import baselines  # noqa: E402
import metrics  # noqa: E402
from roadsense.agent import run  # noqa: E402
from roadsense.bedrock_client import DEFAULT_MODEL_ID  # noqa: E402


def load_cases(path: pathlib.Path, limit: int | None) -> list[dict[str, Any]]:
    cases = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    return cases[:limit] if limit else cases


def run_arm(
    arm: str,
    cases: list[dict[str, Any]],
    *,
    rekognition: Any,
    bedrock: Any,
    model_id: str,
    max_steps: int,
    pricing: dict[str, Any],
    decider_kw: dict[str, Any],
    mask: bool,
) -> dict[str, Any]:
    selector = baselines.build(arm, bedrock=bedrock, model_id=model_id, **decider_kw)
    scores, traces = [], []

    for i, case in enumerate(cases, 1):
        image = str(ROOT / case["image_path"]) if case["image_path"] else None
        t0 = time.perf_counter()
        try:
            result = run(
                case["question"],
                image,
                decider=selector,
                rekognition=rekognition,
                bedrock=bedrock,
                max_steps=max_steps,
                bedrock_model=model_id,
                pricing=pricing,
                mask_illegal_actions=mask,
            )
            trace = result.trace
        except Exception as exc:  # noqa: BLE001 - a crashed case is data, not a stop
            trace = {
                "outcome": "error",
                "answer": "",
                "steps": [],
                "evidence": [],
                "errors": [f"{type(exc).__name__}: {exc}"],
                "wall_ms": (time.perf_counter() - t0) * 1000,
                "cost": {
                    "rekognition_calls": 0, "bedrock_input_tokens": 0,
                    "bedrock_output_tokens": 0, "rekognition_usd": 0.0,
                },
            }
        trace["case_id"] = case["case_id"]
        trace["arm"] = arm
        traces.append(trace)
        scores.append(metrics.score_case(case, trace))
        print(f"  [{arm}] {i}/{len(cases)} {case['case_id']} "
              f"tools={scores[-1]['tools_run']} outcome={trace['outcome']}", flush=True)

    summary = metrics.aggregate(scores)
    if isinstance(selector, baselines.LlmDecider):
        summary["llm_parse_failures"] = selector.parse_failures
    return {"arm": arm, "summary": summary, "scores": scores, "traces": traces}


HEADLINE = [
    ("tool_selection_exact_pct", "Tool set exactly right %", "higher"),
    ("unnecessary_calls_per_case", "Unnecessary calls / case", "lower"),
    ("missing_calls_total", "Missing calls (total)", "lower"),
    ("behavior_correct_pct", "Behaviour correct %", "higher"),
    ("correct_abstention_pct", "Correct on insufficient %", "higher"),
    ("over_abstention_pct", "Over-abstained on answerable %", "lower"),
    ("fidelity_ok_pct", "Answer fidelity ok %", "higher"),
    ("completion_pct", "Completion %", "higher"),
    ("policy_overrides_total", "Policy overrides", "lower"),
    ("steps_per_case", "Steps / case", "lower"),
    ("selector_ms_median", "Selector latency median ms", "lower"),
    ("wall_ms_median", "Wall clock median ms", "lower"),
    ("rekognition_calls_total", "Rekognition calls", "lower"),
    ("rekognition_usd_total", "Rekognition USD", "lower"),
]


def render_report(results: list[dict[str, Any]], cases: int, meta: dict[str, Any]) -> str:
    arms = [r["arm"] for r in results]
    out = [
        "# RoadSense benchmark results",
        "",
        f"Generated by `eval/run_benchmark.py` on {meta['timestamp']}.",
        f"{cases} cases, {len(arms)} arms. Every number below came from this run.",
        "",
        f"- Decider backend: `{meta['decider_backend']}`",
        f"- Bedrock model: `{meta['bedrock_model']}`",
        f"- Step budget: {meta['max_steps']}  |  illegal-action masking: {meta['mask']}",
        "",
        "## Headline",
        "",
        "| Metric | " + " | ".join(arms) + " | better |",
        "|---|" + "---|" * (len(arms) + 1),
    ]
    for key, label, direction in HEADLINE:
        cells = []
        for r in results:
            v = r["summary"].get(key)
            cells.append("n/a" if v is None else (f"{v:g}" if isinstance(v, (int, float)) else str(v)))
        out.append(f"| {label} | " + " | ".join(cells) + f" | {direction} |")

    out += ["", "## Cost and tokens", "",
            "| Metric | " + " | ".join(arms) + " |",
            "|---|" + "---|" * len(arms)]
    for key, label in [
        ("rekognition_calls_total", "Rekognition calls"),
        ("rekognition_usd_total", "Rekognition USD (verified rate)"),
        ("bedrock_input_tokens_total", "Bedrock input tokens"),
        ("bedrock_output_tokens_total", "Bedrock output tokens"),
        ("selector_input_tokens_total", "Selector input tokens"),
        ("selector_output_tokens_total", "Selector output tokens"),
    ]:
        out.append(f"| {label} | " + " | ".join(f"{r['summary'].get(key, 0):g}" for r in results) + " |")
    out += [
        "",
        "Selector tokens are the tool-choosing model's. For the `llm` arm they are "
        "Bedrock tokens billed exactly like the writer's, so that arm's true token "
        "bill is both rows added together. For the `decider` arm they are not billed "
        "per token at all -- Decider 2B runs on an EC2 instance charged by the hour. "
        "The rows are kept apart so those two costs are never silently summed.",
        "",
        "Bedrock cost is reported as token counts, not dollars: no rate for this model "
        "could be verified from the AWS Pricing API or the public pricing page, and "
        "inventing one would make the only priced number in the table the unreliable "
        "one. Add rates to `pricing.json` to price it. The Decider arm additionally "
        "consumes EC2 time, which is an hourly cost on self-managed compute rather "
        "than a per-call charge.",
        "",
        "## Where each arm loses",
        "",
    ]
    for r in results:
        s = r["summary"]
        losses = []
        if s.get("unnecessary_calls_total"):
            losses.append(f"{s['unnecessary_calls_total']} unnecessary tool calls")
        if s.get("missing_calls_total"):
            losses.append(f"{s['missing_calls_total']} missing tool calls")
        if s.get("over_abstention_pct"):
            losses.append(f"over-abstained on {s['over_abstention_pct']}% of answerable cases")
        if s.get("unsupported_quote_cases"):
            losses.append(f"unsupported quoted text in {', '.join(s['unsupported_quote_cases'])}")
        if s.get("policy_overrides_total"):
            losses.append(f"{s['policy_overrides_total']} picks overruled by policy")
        if s.get("llm_parse_failures"):
            losses.append(f"{s['llm_parse_failures']} unparseable selector replies")
        if s.get("error_pct"):
            losses.append(f"{s['error_pct']}% of cases errored")
        out.append(f"- **{r['arm']}**: " + ("; ".join(losses) if losses else "nothing on these metrics."))

    out += ["", "## By difficulty", "",
            "| Arm | " + " | ".join(["easy", "medium", "hard", "invalid-input"]) + " |",
            "|---|---|---|---|---|"]
    for r in results:
        cells = []
        for diff in ("easy", "medium", "hard", "invalid-input"):
            rows = [x for x in r["scores"] if x["difficulty"] == diff]
            ok = sum(x["behavior_correct"] and x["tool_set_exact"] for x in rows)
            cells.append(f"{ok}/{len(rows)}" if rows else "-")
        out.append(f"| {r['arm']} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("Cell shows cases where the tool set *and* the behaviour were both right.")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--arms", nargs="+", default=list(baselines.ARMS))
    ap.add_argument("--cases", default=str(HERE / "cases.jsonl"))
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--max-steps", type=int, default=4)
    ap.add_argument("--region", default="us-east-1")
    ap.add_argument("--bedrock-model", default=DEFAULT_MODEL_ID)
    ap.add_argument("--decider-endpoint", default=None)
    ap.add_argument("--decider-checkpoint", default="StrandsAgents/strands-decider-2B-qwen3.5-v1-2610")
    ap.add_argument("--decider-device", default="cpu")
    ap.add_argument("--no-mask", action="store_true", help="offer illegal actions too")
    ap.add_argument("--no-sufficiency", action="store_true",
                    help="skip the telemetry-only sufficiency question (measurably faster on CPU)")
    ap.add_argument("--out", default=str(HERE / "results"))
    ap.add_argument("--tag", default="", help="suffix for the output filenames")
    args = ap.parse_args(argv)

    import boto3

    rekognition = boto3.client("rekognition", region_name=args.region)
    bedrock = boto3.client("bedrock-runtime", region_name=args.region)
    cases = load_cases(pathlib.Path(args.cases), args.limit)
    pricing = {}

    print(f"{len(cases)} cases x {len(args.arms)} arms = {len(cases) * len(args.arms)} runs")
    results = []
    for arm in args.arms:
        print(f"\n--- arm: {arm} ---", flush=True)
        results.append(
            run_arm(
                arm, cases,
                rekognition=rekognition, bedrock=bedrock, model_id=args.bedrock_model,
                max_steps=args.max_steps, pricing=pricing,
                decider_kw={
                    "endpoint": args.decider_endpoint,
                    "checkpoint": args.decider_checkpoint,
                    "device": args.decider_device,
                    "ask_sufficiency": not args.no_sufficiency,
                },
                mask=not args.no_mask,
            )
        )

    meta = {
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "cases": len(cases),
        "max_steps": args.max_steps,
        "mask": not args.no_mask,
        "bedrock_model": args.bedrock_model,
        "decider_backend": args.decider_endpoint or f"in-process {args.decider_checkpoint} ({args.decider_device})",
    }

    outdir = pathlib.Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)
    tag = f"_{args.tag}" if args.tag else ""
    (outdir / f"results{tag}.json").write_text(
        json.dumps({"meta": meta, "results": results}, indent=2, default=str), encoding="utf-8"
    )
    report = render_report(results, len(cases), meta)
    (outdir / f"report{tag}.md").write_text(report, encoding="utf-8")
    print("\n" + report)
    print(f"\nwrote {outdir / f'results{tag}.json'} and {outdir / f'report{tag}.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
