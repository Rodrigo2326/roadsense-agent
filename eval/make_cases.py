"""Emit eval/cases.jsonl.

Ground truth for ``expected_tools`` is driven by **the question**, not by what the
image happens to contain. "What does the sign say?" needs OCR whether or not the sign
turns out to be readable; that is precisely the point -- the agent has to find out.

``expected_behavior`` is driven by what the tools can actually deliver, measured
against the live Rekognition API (see ``scripts/make_assets.py``):

* ``answer``        -- the evidence available does answer the question.
* ``insufficient``  -- it does not, and the honest run either asks for better
                       evidence or states the limit in the answer.

Fields per line: case_id, question, image_path, expected_tools, expected_behavior,
difficulty, notes, source.
"""

from __future__ import annotations

import json
import pathlib

SOURCE = "synthetic, generated by scripts/make_assets.py, Apache-2.0 (own work)"
IMG = "demo/images"

DETECT = ["detect_objects"]
OCR = ["read_sign_text"]
BOTH = ["detect_objects", "read_sign_text"]

Q_DETECT = "What objects are visible in this scene?"
Q_VEHICLES = "Are there any vehicles in this photo?"
Q_PEOPLE = "Are there any people in this image?"
Q_OCR = "What text can be read on the sign?"
Q_SAYS = "What does the sign say?"
Q_BOTH = "What vehicles appear and what text can be read on the sign?"
Q_LIST = "List the objects you can see and read any sign text."

# (image, question, expected_tools, expected_behavior, difficulty, notes)
ROWS = [
    # --- detection only -------------------------------------------------------
    ("synthetic_sign_clear.jpg", Q_DETECT, DETECT, "answer", "easy", "detector sees road, sign, symbol"),
    ("synthetic_sign_clear.jpg", Q_PEOPLE, DETECT, "answer", "easy", "no people present; answer is a negative"),
    ("synthetic_sign_and_vehicles.jpg", Q_DETECT, DETECT, "answer", "easy", ""),
    ("synthetic_vehicles_no_sign.jpg", Q_VEHICLES, DETECT, "insufficient", "hard",
     "drawn cars are NOT labelled as vehicles by Rekognition; evidence cannot confirm the question"),
    ("synthetic_empty_road.jpg", Q_DETECT, DETECT, "answer", "easy", "nature/sky/road only"),
    ("synthetic_sign_night.jpg", Q_DETECT, DETECT, "answer", "medium", ""),
    ("synthetic_speed_limit.jpg", Q_DETECT, DETECT, "answer", "easy", ""),
    ("synthetic_roadwork.jpg", Q_VEHICLES, DETECT, "insufficient", "hard",
     "same drawn-vehicle limitation as above"),
    ("synthetic_sign_illegible.jpg", Q_DETECT, DETECT, "answer", "medium",
     "detection still works on a degraded image even though OCR does not"),

    # --- OCR only -------------------------------------------------------------
    ("synthetic_sign_clear.jpg", Q_OCR, OCR, "answer", "easy", "reads STOP AHEAD at ~1.00"),
    ("synthetic_sign_and_vehicles.jpg", Q_SAYS, OCR, "answer", "easy", ""),
    ("synthetic_speed_limit.jpg", Q_OCR, OCR, "answer", "easy", "reads SPEED LIMIT 50"),
    ("synthetic_roadwork.jpg", Q_SAYS, OCR, "answer", "easy", "reads ROAD WORK"),
    ("synthetic_sign_night.jpg", Q_OCR, OCR, "answer", "medium", "low light, still legible"),
    ("synthetic_sign_occluded.jpg", Q_OCR, OCR, "answer", "medium",
     "foliage hides the second line; OCR returns STOP only"),
    ("synthetic_sign_partial.jpg", Q_OCR, OCR, "answer", "hard",
     "degraded to 88px: reads STOP, loses AHEAD"),
    ("synthetic_sign_garbled.jpg", Q_OCR, OCR, "insufficient", "hard",
     "degraded to 65px: OCR returns 'I' at 0.854 -- confidently WRONG, above any sane threshold"),
    ("synthetic_sign_illegible.jpg", Q_OCR, OCR, "insufficient", "hard",
     "degraded to 45px: OCR returns nothing at all"),
    ("synthetic_vehicles_no_sign.jpg", Q_SAYS, OCR, "insufficient", "medium", "there is no sign"),
    ("synthetic_empty_road.jpg", Q_OCR, OCR, "insufficient", "medium", "there is no sign"),

    # --- both tools -----------------------------------------------------------
    ("synthetic_sign_clear.jpg", Q_BOTH, BOTH, "answer", "medium", "the canonical two-step case"),
    ("synthetic_sign_and_vehicles.jpg", Q_BOTH, BOTH, "insufficient", "hard",
     "sign reads, but the drawn vehicles are not detected as vehicles"),
    ("synthetic_sign_clear.jpg", Q_LIST, BOTH, "answer", "medium", ""),
    ("synthetic_speed_limit.jpg", Q_LIST, BOTH, "answer", "medium", ""),
    ("synthetic_roadwork.jpg", Q_BOTH, BOTH, "insufficient", "hard", "drawn vehicle not detected"),
    ("synthetic_sign_night.jpg", Q_LIST, BOTH, "answer", "medium", ""),
    ("synthetic_sign_occluded.jpg", Q_LIST, BOTH, "answer", "hard", "partial sign text"),
    ("synthetic_sign_partial.jpg", Q_BOTH, BOTH, "insufficient", "hard", "partial text and no vehicles"),
    ("synthetic_sign_garbled.jpg", Q_LIST, BOTH, "insufficient", "hard", "garbled OCR"),
    ("synthetic_sign_illegible.jpg", Q_BOTH, BOTH, "insufficient", "hard", "no text, no vehicles"),
    ("synthetic_empty_road.jpg", Q_LIST, BOTH, "insufficient", "medium", "nothing to read"),
    ("synthetic_vehicles_no_sign.jpg", Q_BOTH, BOTH, "insufficient", "hard", ""),
]

# Inputs no tool can run on. ``expected_tools`` is empty: the correct number of
# vision calls here is zero, and spending one is a measurable mistake.
INVALID = [
    ("missing_file.jpg", Q_OCR, "insufficient", "the path does not exist"),
    ("missing_file.jpg", Q_DETECT, "insufficient", "the path does not exist"),
    ("not_an_image.txt", Q_OCR, "insufficient", "wrong file type"),
    ("empty_file.jpg", Q_DETECT, "insufficient", "zero-byte file"),
    (None, Q_BOTH, "insufficient", "no image argument at all"),
]


def build() -> list[dict]:
    cases: list[dict] = []
    for i, (img, q, tools, behavior, difficulty, notes) in enumerate(ROWS, start=1):
        cases.append(
            {
                "case_id": f"rs-{i:03d}",
                "question": q,
                "image_path": f"{IMG}/{img}",
                "expected_tools": tools,
                "expected_behavior": behavior,
                "difficulty": difficulty,
                "notes": notes,
                "source": SOURCE,
            }
        )
    for j, (img, q, behavior, notes) in enumerate(INVALID, start=len(ROWS) + 1):
        cases.append(
            {
                "case_id": f"rs-{j:03d}",
                "question": q,
                "image_path": f"{IMG}/{img}" if img else None,
                "expected_tools": [],
                "expected_behavior": behavior,
                "difficulty": "invalid-input",
                "notes": notes,
                "source": "n/a",
            }
        )
    return cases


if __name__ == "__main__":
    out = pathlib.Path(__file__).resolve().parent / "cases.jsonl"
    cases = build()
    out.write_text(
        "\n".join(json.dumps(c, ensure_ascii=False) for c in cases) + "\n", encoding="utf-8"
    )
    by_diff: dict[str, int] = {}
    by_behavior: dict[str, int] = {}
    for c in cases:
        by_diff[c["difficulty"]] = by_diff.get(c["difficulty"], 0) + 1
        by_behavior[c["expected_behavior"]] = by_behavior.get(c["expected_behavior"], 0) + 1
    print(f"wrote {len(cases)} cases to {out}")
    print("  by difficulty:", by_diff)
    print("  by expected behavior:", by_behavior)
